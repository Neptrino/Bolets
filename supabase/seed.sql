cells as (
  select
    bucket_x,
    ranges.bucket_y,
    ranges.region_id,
    extensions.st_transform(
      extensions.st_makeenvelope(
        bucket_x * 10000,
        ranges.bucket_y * 10000,
        (bucket_x + 1) * 10000,
        (ranges.bucket_y + 1) * 10000,
        25831
      ),
      4326
    ) as geographic_cell
  from cell_ranges ranges
  cross join lateral generate_series(ranges.min_x, ranges.max_x) bucket_x
)
