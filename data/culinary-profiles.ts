const ratingLabels: Record<0 | 1 | 2 | 3, string> = {
  0: "No consumible",
  1: "Acceptable",
  2: "Molt bo",
  3: "Excel·lent",
};

type CulinarySeed = Omit<CulinaryProfile & { kind: "culinary" }, "kind" | "ratingLabel" | "sources">;
type SafetySeed = Omit<CulinaryProfile & { kind: "safety" }, "kind" | "rating" | "ratingLabel" | "sources">;

function culinary(seed: CulinarySeed): CulinaryProfile {
  return {
    ...seed,
    kind: "culinary",
    ratingLabel: ratingLabels[seed.rating],
    sources: [scmQuality, catalanFoodGuide, acsaSafety],
  };
}

function safety(seed: SafetySeed): CulinaryProfile {
  return {
    ...seed,
    kind: "safety",
    rating: 0,
    ratingLabel: ratingLabels[0],
    sources: [scmQuality, acsaSafety],
  };
}

